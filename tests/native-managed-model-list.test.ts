import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import Ajv from 'ajv'
import { nativeManagedModelList } from '../packages/cli/src/launcher/native-managed-model-list.js'
import type { NativeModelProviderCatalogEntry } from '../packages/cli/src/launcher/native-model-provider-catalog.js'

const provider = (count = 2): NativeModelProviderCatalogEntry => ({
  providerId: 'plugin-a',
  pluginId: 'plugin',
  defaultModelId: 'model-0',
  models: Array.from({ length: count }, (_, index) => ({
    id: `model-${index}`,
    label: `Model ${index}`,
    aliases: [],
    reasoningCapabilities: { efforts: ['low', 'high'], defaultEffort: 'high' },
  })),
})

describe('native managed model-list recovery', () => {
  it('projects only a locally owned, available provider and preserves its models and efforts', async () => {
    const list = nativeManagedModelList({ owns: id => id === 'plugin-a', catalog: async () => [provider()] })
    expect(await list({ providerId: 'openai' })).toBeUndefined()
    expect(await list({ providerId: 'plugin-a' })).toEqual({
      data: [0, 1].map(index => ({
        id: `model-${index}`,
        model: `model-${index}`,
        displayName: `Model ${index}`,
        description: '',
        hidden: false,
        isDefault: index === 0,
        defaultReasoningEffort: 'high',
        supportedReasoningEfforts: [
          { reasoningEffort: 'low', description: '' },
          { reasoningEffort: 'high', description: '' },
        ],
        inputModalities: ['text', 'image', 'audio'],
        serviceTiers: [],
      })),
      nextCursor: null,
    })
  })

  it('conforms to Codex 0.171 ModelListResponse and leaves unknown input types unblocked', async () => {
    // Generated by `codex app-server generate-json-schema --experimental` from
    // the user's 0.171.0-alpha.13 app-server. The checked-in fixture makes the
    // test independent of an installed Codex application or user credentials.
    const schema = JSON.parse(
      readFileSync(new URL('./fixtures/codex-0.171-model-list-response.schema.json', import.meta.url), 'utf8'),
    )
    const validate = new Ajv({ strict: false, validateFormats: false }).compile(schema)
    const list = nativeManagedModelList({ owns: id => id === 'plugin-a', catalog: async () => [provider(205)] })
    const first = await list({ providerId: 'plugin-a', limit: 100 }) as {
      data: { inputModalities: string[] }[]
      nextCursor: string
    }
    expect(validate(first), JSON.stringify(validate.errors)).toBe(true)
    expect(first.data).toHaveLength(100)
    expect(first.data.every(model => JSON.stringify(model.inputModalities) === '["text","image","audio"]')).toBe(true)
    const second = await list({ providerId: 'plugin-a', limit: 100, cursor: first.nextCursor }) as {
      data: unknown[]
      nextCursor: string
    }
    expect(validate(second), JSON.stringify(validate.errors)).toBe(true)
    expect(second.data).toHaveLength(100)
    const last = await list({ providerId: 'plugin-a', limit: 100, cursor: second.nextCursor }) as {
      data: unknown[]
      nextCursor: null
    }
    expect(validate(last), JSON.stringify(validate.errors)).toBe(true)
    expect(last.data).toHaveLength(5)
    expect(last.nextCursor).toBeNull()
  })

  it('does not fabricate missing capabilities or a default and does not reuse stale pages', async () => {
    let current = provider(2)
    const list = nativeManagedModelList({ owns: () => true, catalog: async () => [current] })
    const first = await list({ providerId: 'plugin-a', limit: 1 }) as { nextCursor: string }
    expect(first.nextCursor).toMatch(/^cx-model-v1:/)
    expect(await list({ providerId: 'plugin-a', cursor: first.nextCursor, limit: 1 })).toMatchObject({
      data: [{ id: 'model-1' }],
      nextCursor: null,
    })
    current = provider(3)
    expect(await list({ providerId: 'plugin-a', cursor: first.nextCursor, limit: 1 })).toBeUndefined()
    current = { ...provider(), models: [{ id: 'unknown', label: 'Unknown', aliases: [] }] }
    expect(await list({ providerId: 'plugin-a' })).toBeUndefined()
    current = {
      ...provider(),
      models: [{
        id: 'incomplete',
        label: 'Incomplete',
        aliases: [],
        reasoningCapabilities: { efforts: ['low', 'high'] },
      }],
    }
    expect(await list({ providerId: 'plugin-a' })).toBeUndefined()
  })

  it('rejects malformed cursors, limits, unknown providers, and unavailable catalogs', async () => {
    const list = nativeManagedModelList({ owns: () => true, catalog: async () => [provider()] })
    expect(await list({ providerId: 'other' })).toBeUndefined()
    expect(await list({ providerId: 'plugin-a', limit: 0 })).toBeUndefined()
    expect(await list({ providerId: 'plugin-a', cursor: 'native-cursor' })).toBeUndefined()
    const unavailable = nativeManagedModelList({ owns: () => true, catalog: async () => [] })
    expect(await unavailable({ providerId: 'plugin-a' })).toBeUndefined()
  })
})
