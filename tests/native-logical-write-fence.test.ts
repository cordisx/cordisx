import { describe, expect, it } from 'vitest'
import { NativeLogicalWriteFence } from '../packages/cli/assets/launcher/native-logical-write-fence.mjs'
import { NativeLogicalDestinationReservations } from '../packages/cli/assets/launcher/native-logical-destination-reservations.mjs'

describe('native intermediary write fence', () => {
  it('waits for an actual response and blocks writes while a migration owns the source', () => {
    const fence = new NativeLogicalWriteFence()
    const write = { id: 1, method: 'turn/start', params: { threadId: 'source' } }
    fence.enter(write)
    expect(fence.acquire('source')).toBeUndefined()
    fence.complete({ id: 1, method: 'item/tool/call' })
    expect(fence.acquire('source')).toBeUndefined()
    fence.complete({ id: 1, error: { code: -32000 } })
    const lease = fence.acquire('source')!
    expect(() => fence.enter({ ...write, id: 2 })).toThrow('Native continuation pending')
    expect(() => fence.enter({ ...write, id: 3 }, lease)).not.toThrow()
    expect(() => fence.enter({ id: 4, method: 'thread/read', params: { threadId: 'source' } })).not.toThrow()
    expect(fence.release('source', 'wrong')).toBe(false)
    expect(fence.release('source', lease)).toBe(false)
    fence.complete({ id: 3, error: { code: -32000 } })
    expect(fence.release('source', lease)).toBe(true)
    expect(fence.release('source', lease)).toBe(false)
  })
  it('never permits migration after uncorrelatable writes', () => {
    const fence = new NativeLogicalWriteFence()
    fence.enter({ method: 'turn/start', params: { threadId: 'source' } })
    expect(fence.acquire('source')).toBeUndefined()
    expect(fence.acquire('other')).toBeUndefined()
  })
  it('retains uncertainty when a transport failure synthesizes a response to a write', () => {
    const fence = new NativeLogicalWriteFence()
    fence.enter({ id: 1, method: 'turn/start', params: { threadId: 'source' } })
    fence.uncertain(1)
    fence.complete({ id: 1, error: { code: -32000 } })
    expect(fence.acquire('source')).toBeUndefined()
    expect(fence.acquire('other')).toBeUndefined()
  })
  it('does not fence migrations after an uncertain read', () => {
    const fence = new NativeLogicalWriteFence()
    fence.enter({ id: 1, method: 'thread/read', params: { threadId: 'source' } })
    fence.uncertain(1)
    fence.complete({ id: 1, error: { code: -32000 } })
    expect(fence.acquire('source')).toBeDefined()
  })
  it('blocks until an accepted turn completes, including completion before the reply', () => {
    const fence = new NativeLogicalWriteFence()
    fence.enter({ id: 1, method: 'turn/start', params: { threadId: 'source' } })
    fence.complete({ id: 1, result: { turn: { id: 'turn-1', status: 'inProgress' } } })
    expect(fence.acquire('source')).toBeUndefined()
    fence.complete({ method: 'turn/completed', params: { threadId: 'source', turn: { id: 'turn-1' } } })
    const lease = fence.acquire('source')!
    expect(fence.release('source', lease)).toBe(true)
    fence.enter({ id: 2, method: 'turn/start', params: { threadId: 'source' } })
    fence.complete({ method: 'turn/started', params: { threadId: 'source', turn: { id: 'turn-2' } } })
    fence.complete({ method: 'turn/completed', params: { threadId: 'source', turn: { id: 'turn-2' } } })
    fence.complete({ id: 2, result: { turn: { id: 'turn-2', status: 'inProgress' } } })
    expect(fence.acquire('source')).toBeDefined()
  })
  it('fences a late creation reply even if the original caller has timed out', () => {
    const fence = new NativeLogicalWriteFence()
    const reservations = new NativeLogicalDestinationReservations(fence)
    reservations.register('timed-out')
    reservations.observe({ id: 'timed-out', result: { thread: { id: 'destination' } } })
    expect(() => fence.enter({ id: 2, method: 'turn/start', params: { threadId: 'destination' } }))
      .toThrow('Native continuation pending')
    expect(fence.acquire('destination')).toBeUndefined()
  })
  it('holds the source lease while a new native destination is still being created', () => {
    const fence = new NativeLogicalWriteFence()
    const lease = fence.acquire('source')!
    fence.enter({ id: 1, method: 'thread/start', params: {} }, lease, 'source')
    expect(fence.release('source', lease)).toBe(false)
    fence.complete({ id: 1, result: { thread: { id: 'destination' } } })
    expect(fence.release('source', lease)).toBe(true)
  })
  it('restores durable unknown-source fences and rejects stale updates', () => {
    const fence = new NativeLogicalWriteFence()
    expect(fence.restore(4, ['source'])).toBe(true)
    expect(fence.acquire('source')).toBeUndefined()
    expect(() => fence.enter({ id: 1, method: 'turn/start', params: { threadId: 'source' } }))
      .toThrow('Native continuation pending')
    expect(fence.restore(3, [])).toBe(false)
    expect(fence.restore(4, [])).toBe(false)
    expect(fence.restore(5, [])).toBe(true)
    expect(fence.acquire('source')).toBeDefined()
  })
  it('keeps migration unavailable if recovery finds an already active source write', () => {
    const fence = new NativeLogicalWriteFence()
    fence.enter({ id: 1, method: 'turn/start', params: { threadId: 'source' } })
    expect(fence.restore(1, ['source'])).toBe(true)
    expect(fence.canAbandon(['source'])).toBe(false)
    fence.complete({ id: 1, error: { code: -32000 } })
    expect(fence.restore(2, [])).toBe(true)
    expect(fence.acquire('source')).toBeUndefined()
  })
  it('permits recovery only for persisted fences without live leases or uncertain writes', () => {
    const fence = new NativeLogicalWriteFence()
    expect(fence.restore(1, ['source', 'target'])).toBe(true)
    expect(fence.canAbandon(['source', 'target'])).toBe(true)
    expect(fence.canAbandon(['source', 'other'])).toBe(false)
    expect(fence.canAbandon(['source', 'source'])).toBe(false)
    expect(fence.canAbandon([])).toBe(false)
    const active = new NativeLogicalWriteFence()
    const lease = active.acquire('source')!
    expect(active.restore(1, ['source'])).toBe(true)
    expect(active.canAbandon(['source'])).toBe(false)
    expect(active.release('source', lease)).toBe(false)
  })
})
