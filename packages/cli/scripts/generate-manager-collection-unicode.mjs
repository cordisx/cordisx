import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const unicodeVersion = '17.0.0'
const base = `https://www.unicode.org/Public/${unicodeVersion}/ucd`
const sources = {
  derived: `${base}/DerivedNormalizationProps.txt`,
  unicodeData: `${base}/UnicodeData.txt`,
}

async function read(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`Unable to download ${url}: ${response.status}`)
  return await response.text()
}

function codePoint(value) {
  return Number.parseInt(value, 16)
}
function hex(value) {
  return value.toString(16).toUpperCase()
}

const [derived, unicodeData] = await Promise.all([read(sources.derived), read(sources.unicodeData)])
const nfkc = []
const exclusions = new Set()
for (const raw of derived.split(/\r?\n/u)) {
  const line = raw.replace(/#.*/u, '').trim()
  if (line === '') continue
  const [rangeText, property, mappingText = ''] = line.split(';').map(value => value.trim())
  if (property === 'Full_Composition_Exclusion') {
    const [startText, endText = startText] = rangeText.split('..')
    for (let value = codePoint(startText); value <= codePoint(endText); value += 1) exclusions.add(value)
    continue
  }
  if (property !== 'NFKC_CF') continue
  const [startText, endText = startText] = rangeText.split('..')
  const mapping = mappingText === ''
    ? ''
    : mappingText.split(/\s+/u).map(value => String.fromCodePoint(codePoint(value))).join('')
  for (let value = codePoint(startText); value <= codePoint(endText); value += 1) nfkc.push([value, mapping])
}

const combining = []
const decomposition = []
for (const line of unicodeData.split(/\r?\n/u)) {
  if (line === '') continue
  const fields = line.split(';')
  const value = codePoint(fields[0])
  const ccc = Number.parseInt(fields[3], 10)
  if (ccc !== 0) combining.push([value, ccc])
  const rawDecomposition = fields[5]
  if (rawDecomposition === '' || rawDecomposition.startsWith('<')) continue
  decomposition.push([value, rawDecomposition.split(/\s+/u).map(codePoint)])
}

const composition = []
for (const [composed, mapping] of decomposition) {
  if (mapping.length !== 2 || exclusions.has(composed)) continue
  composition.push([mapping[0], mapping[1], composed])
}

const hashes = Object.fromEntries([
  ['DerivedNormalizationProps.txt', derived],
  ['UnicodeData.txt', unicodeData],
].map(([name, value]) => [name, createHash('sha256').update(value).digest('hex')]))

const source = `// Generated by packages/cli/scripts/generate-manager-collection-unicode.mjs.
// Unicode ${unicodeVersion}; do not hand-edit.
// DerivedNormalizationProps.txt sha256 ${hashes['DerivedNormalizationProps.txt']}
// UnicodeData.txt sha256 ${hashes['UnicodeData.txt']}

export const UNICODE_MANAGER_COLLECTION_VERSION = '${unicodeVersion}' as const

export const NFKC_CASEFOLD_MAPPINGS = new Map<number, string>(${JSON.stringify(nfkc)})
export const CANONICAL_COMBINING_CLASSES = new Map<number, number>(${JSON.stringify(combining)})
export const CANONICAL_DECOMPOSITIONS = new Map<number, readonly number[]>(${JSON.stringify(decomposition)})
export const CANONICAL_COMPOSITIONS = new Map<string, number>(${
  JSON.stringify(composition.map(([left, right, composed]) => [String(left) + ':' + String(right), composed]))
})
`

const output = fileURLToPath(new URL('../src/renderer/manager-collection-unicode-17.generated.ts', import.meta.url))
await writeFile(output, source)
console.log(`Wrote ${output}; ${nfkc.length} NFKC_CF mappings, ${composition.length} compositions.`)
