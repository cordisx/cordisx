import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const destination = path.join(packageRoot, 'src/renderer/manager/data/contributors.generated.ts')
const inputPath = process.argv[2]
const raw = inputPath === undefined
  ? process.env.CORDISX_CONTRIBUTORS_JSON
  : await readFile(path.resolve(process.cwd(), inputPath), 'utf8')

if (raw === undefined || raw.trim() === '') {
  throw new Error('Provide a JSON file path or CORDISX_CONTRIBUTORS_JSON')
}

const source = JSON.parse(raw)
if (!Array.isArray(source) || source.length > 500) {
  throw new Error('Contributor data must be an array with at most 500 entries')
}

const text = (value, label, max) => {
  if (typeof value !== 'string' || value.trim() === '' || value.length > max) {
    throw new Error(`${label} must be a non-empty string of at most ${max} characters`)
  }
  return value.trim()
}
const httpsUrl = (value, label) => {
  if (value === undefined) return undefined
  const url = new URL(text(value, label, 500))
  if (url.protocol !== 'https:') throw new Error(`${label} must use https`)
  return url.href
}

const contributors = source.map((entry, index) => {
  if (entry === null || typeof entry !== 'object' || Array.isArray(entry)) {
    throw new Error(`contributors[${index}] must be an object`)
  }
  const contribution = entry.contribution
  if (contribution === null || typeof contribution !== 'object' || Array.isArray(contribution)) {
    throw new Error(`contributors[${index}].contribution must be an object`)
  }
  const profileUrl = httpsUrl(entry.profileUrl, `contributors[${index}].profileUrl`)
  const avatarUrl = httpsUrl(entry.avatarUrl, `contributors[${index}].avatarUrl`)
  return {
    name: text(entry.name, `contributors[${index}].name`, 80),
    contribution: {
      en: text(contribution.en, `contributors[${index}].contribution.en`, 160),
      'zh-CN': text(contribution['zh-CN'], `contributors[${index}].contribution.zh-CN`, 160),
    },
    ...(profileUrl === undefined ? {} : { profileUrl }),
    ...(avatarUrl === undefined ? {} : { avatarUrl }),
  }
})

const output =
  `// Generated by scripts/generate-contributors.mjs. CI may replace this file before build.\nexport const ACKNOWLEDGEMENT_CONTRIBUTORS = ${
    JSON.stringify(contributors, null, 2)
  } as const\n`
await writeFile(destination, output)
console.log(`[cordisx] wrote ${path.relative(packageRoot, destination)} with ${contributors.length} contributor(s)`)
