const ZH_CAPABILITY_MESSAGES = Object.freeze(Object.fromEntries(HOST_CAPABILITY_RISK_ENTRIES.flatMap(entry => (
  Object.values(entry.presentation).map(message => [
    message.key,
    ZH_PREFIXED_CAPABILITY_MESSAGES[`permission.${message.key}`],
  ])
))))

const EN_CAPABILITY_MESSAGES = Object.freeze(Object.fromEntries(HOST_CAPABILITY_RISK_ENTRIES.flatMap(entry => [
  [entry.presentation.name.key, entry.presentation.name.fallback ?? entry.capability],
  [entry.presentation.description.key, entry.presentation.description.fallback ?? entry.capability],
  [entry.presentation.risk.key, entry.presentation.risk.fallback ?? entry.capability],
  [entry.presentation.limitation.key, entry.presentation.limitation.fallback ?? entry.capability],
])))

export const CORDISX_PERMISSION_LOCALE_CATALOGS: readonly CordisXLocaleCatalog[] = Object.freeze([
  Object.freeze({
    namespace: CORDISX_PERMISSION_NAMESPACE,
    locale: 'en',
    default: true,
    messages: Object.freeze({ ...EN_UI_MESSAGES, ...EN_CAPABILITY_MESSAGES }),
  }),
  Object.freeze({
    namespace: CORDISX_PERMISSION_NAMESPACE,
    locale: 'zh-CN',
    messages: Object.freeze({ ...ZH_UI_MESSAGES, ...ZH_CAPABILITY_MESSAGES }),
  }),
])

/** Resolve the Host-owned capability name from the same catalogs used by permission review. */
export function projectPermissionCapabilityName(capability: CordisXPermissionCapabilityV4, locale: string): string {
  const presentation = HOST_CAPABILITY_RISK_ENTRIES.find(entry => entry.capability === capability)?.presentation.name
  if (presentation === undefined) return capability
  const messages = new Intl.Locale(locale).language === 'zh' ? ZH_CAPABILITY_MESSAGES : EN_CAPABILITY_MESSAGES
  return messages[presentation.key] ?? presentation.fallback ?? capability
}
